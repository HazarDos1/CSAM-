const DICTS = { en: EN, fr: FR };

let current = (() => {
	try {
		const saved = localStorage.getItem(STORAGE_KEY);
		if (LANGS.includes(saved)) return saved;
	} catch (err) { /* stockage indisponible : on reste sur la valeur par défaut */ }
	return 'en';
})();

/**
 * @param {string} key clé du dictionnaire
 * @param {object} [vars] valeurs à injecter dans les {placeholders}
 * @returns {string} le texte traduit, ou l'anglais, ou la clé
 */
function t(key, vars) {
	let s = DICTS[current][key];
	if (s === undefined) s = EN[key];
	if (s === undefined) return key;
	if (!vars) return s;
	return s.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : vars[name]));
}

function getLang() { return current; }

function setLang(lang) {
	if (!LANGS.includes(lang)) return current;
	current = lang;
	try { localStorage.setItem(STORAGE_KEY, lang); } catch (err) { /* sans persistance, tant pis */ }
	document.documentElement.lang = lang;
	applyStatic();
	return current;
}

/** Applique les traductions au balisage statique de index.html. */
function applyStatic(root = document) {
	for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
	for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
	for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
	for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

window.i18n = { t, getLang, setLang, applyStatic, LANGS, DICTS };
